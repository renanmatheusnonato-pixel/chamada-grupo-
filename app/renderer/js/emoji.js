  function codePoints(str) {
    // Regra do Twemoji: sem ZWJ, o seletor de variação FE0F sai do nome do arquivo
    const clean = str.includes('‍') ? str : str.replace(/️/g, '');
    return [...clean].map((c) => c.codePointAt(0).toString(16)).join('-');
  }
